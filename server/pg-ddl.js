// Tools → Databases → Design: changes to a table's structure as a list of operations, turned into SQL here
// (names quoted, types and expressions checked), shown before anything runs, then run together in ONE transaction
// — "test" runs them and rolls back, so a failing change (a type that does not fit the data, a duplicate key for a
// new unique index …) is seen before it is made. CREATE / DROP INDEX CONCURRENTLY can not run in a transaction:
// they run one by one after the rest (and without CONCURRENTLY in a test).
//   build(ops, { schema, table, structure })  → [{ sql, label, concurrent }]
//   preview(name, db, body) → { statements }      apply(name, db, { schema, table, ops, test }) → { ok, test, statements }
const P = require('./pg-sql');

const err = (msg, statusCode = 400, extra) => Object.assign(new Error(msg), { statusCode }, extra || {});
const id = P.ident;
const lit = (s) => P.lit(String(s));
// types: "integer", "character varying(255)", "numeric(12,2)", "timestamp with time zone", "text[]", "public.mood"
const TYPE_RE = /^[A-Za-z_][\w$]*(\.[A-Za-z_][\w$]*)?( [A-Za-z_]+)*(\s*\(\s*\d+\s*(,\s*\d+\s*)?\))?( (with|without) time zone)?(\[\d*\])*$/;
const NAME_RE = /^[^\0]{1,63}$/;
const ACTIONS = ['NO ACTION', 'RESTRICT', 'CASCADE', 'SET NULL', 'SET DEFAULT'];
const METHODS = ['btree', 'hash', 'gin', 'gist', 'brin', 'spgist'];

function name(n, what = 'name') { const s = String(n == null ? '' : n).trim(); if (!NAME_RE.test(s)) throw err(`A ${what} is needed (at most 63 characters)`); return s; }
function type(t) { const s = String(t || '').trim().replace(/\s+/g, ' '); if (!TYPE_RE.test(s)) throw err(`"${s || '(empty)'}" is not a type DockGate can use — e.g. text, integer, numeric(12,2), timestamptz, varchar(100), uuid, jsonb, text[]`); return s; }
/** A default / USING / CHECK expression: anything but a second statement. */
function expr(e, what) {
  const s = String(e == null ? '' : e).trim();
  if (!s) throw err(`${what}: an expression is needed`);
  const bare = s.replace(/'([^']|'')*'/g, "''").replace(/"([^"]|"")*"/g, '""');
  if (bare.includes(';') || /--|\/\*/.test(bare)) throw err(`${what}: one expression, without ; or comments`);
  return s;
}
const cols = (list, what) => { if (!Array.isArray(list) || !list.length) throw err(`${what}: pick at least one column`); return list.map(c => id(name(c, 'column'))).join(', '); };
const autoName = (...p) => p.join('_').replace(/[^\w]+/g, '_').slice(0, 63);

function colDef(c) {
  let s = `${id(name(c.name, 'column name'))} ${type(c.type)}`;
  if (c.identity) s += ' GENERATED BY DEFAULT AS IDENTITY';
  if (c.notnull || c.pk) s += ' NOT NULL';
  if (c.default != null && String(c.default).trim() !== '' && !c.identity) s += ` DEFAULT ${expr(c.default, `${c.name} default`)}`;
  return s;
}

/** Operations → statements. structure: the table as pg-studio.structure returns it (needed for changes to an existing table). */
function build(ops, { schema, table, structure } = {}) {
  if (!Array.isArray(ops) || !ops.length) throw err('No changes');
  if (ops.length > 200) throw err('At most 200 changes at once');
  const out = [];
  const add = (sql, label, extra) => out.push({ sql, label, ...(extra || {}) });
  const q = schema && table ? P.qname(schema, table) : null;
  const have = new Set(((structure && structure.columns) || []).map(c => c.name));
  const mustHave = (c) => { if (structure && !have.has(c)) throw err(`There is no column ${c}`); return c; };
  for (const op of ops) {
    switch (op && op.op) {
      case 'createTable': {
        const s = name(op.schema || schema || 'public', 'schema'); const n = name(op.name, 'table name');
        const list = op.columns || []; if (!list.length) throw err('Add at least one column');
        const seen = new Set(); list.forEach(c => { const k = String(c.name).trim(); if (seen.has(k)) throw err(`Column ${k} is twice`); seen.add(k); });
        const pk = list.filter(c => c.pk).map(c => id(c.name));
        const lines = list.map(colDef);
        if (pk.length) lines.push(`PRIMARY KEY (${pk.join(', ')})`);
        list.filter(c => c.unique && !c.pk).forEach(c => lines.push(`UNIQUE (${id(c.name)})`));
        add(`CREATE TABLE ${P.qname(s, n)} (\n  ${lines.join(',\n  ')}\n)`, `create table ${s}.${n}`);
        if (op.comment) add(`COMMENT ON TABLE ${P.qname(s, n)} IS ${lit(op.comment)}`, 'table comment');
        list.filter(c => c.comment).forEach(c => add(`COMMENT ON COLUMN ${P.qname(s, n)}.${id(c.name)} IS ${lit(c.comment)}`, `comment on ${c.name}`));
        break;
      }
      case 'addColumn': {
        if (structure && have.has(String(op.name).trim())) throw err(`There is already a column ${String(op.name).trim()}`);
        add(`ALTER TABLE ${q} ADD COLUMN ${colDef(op)}`, `add column ${op.name}`);
        if (op.unique) add(`ALTER TABLE ${q} ADD UNIQUE (${id(op.name)})`, `unique ${op.name}`);
        if (op.comment) add(`COMMENT ON COLUMN ${q}.${id(op.name)} IS ${lit(op.comment)}`, `comment on ${op.name}`);
        break;
      }
      case 'alterColumn': {
        const c = mustHave(name(op.name, 'column')); const cq = id(c);
        if (op.type) add(`ALTER TABLE ${q} ALTER COLUMN ${cq} TYPE ${type(op.type)}${op.using ? ` USING ${expr(op.using, `${c} USING`)}` : ''}`, `${c}: type ${op.type}`);
        if (op.identity === false) add(`ALTER TABLE ${q} ALTER COLUMN ${cq} DROP IDENTITY IF EXISTS`, `${c}: no identity`);
        if (op.default !== undefined) add(op.default === null || String(op.default).trim() === '' ? `ALTER TABLE ${q} ALTER COLUMN ${cq} DROP DEFAULT` : `ALTER TABLE ${q} ALTER COLUMN ${cq} SET DEFAULT ${expr(op.default, `${c} default`)}`, `${c}: default`);
        if (op.identity === true) add(`ALTER TABLE ${q} ALTER COLUMN ${cq} ADD GENERATED BY DEFAULT AS IDENTITY`, `${c}: identity`);
        if (op.notnull === true) add(`ALTER TABLE ${q} ALTER COLUMN ${cq} SET NOT NULL`, `${c}: not null`);
        if (op.notnull === false) add(`ALTER TABLE ${q} ALTER COLUMN ${cq} DROP NOT NULL`, `${c}: null allowed`);
        if (op.comment !== undefined) add(`COMMENT ON COLUMN ${q}.${cq} IS ${op.comment ? lit(op.comment) : 'NULL'}`, `${c}: comment`);
        if (op.rename && op.rename !== c && have.has(op.rename) && !ops.some(o => o.op === 'alterColumn' && o.name === op.rename && o.rename && o.rename !== op.rename) && !ops.some(o => o.op === 'dropColumn' && o.name === op.rename)) throw err(`There is already a column ${op.rename}`);
        if (op.rename && op.rename !== c) add(`ALTER TABLE ${q} RENAME COLUMN ${cq} TO ${id(name(op.rename, 'new column name'))}`, `${c} → ${op.rename}`);
        break;
      }
      case 'dropColumn': add(`ALTER TABLE ${q} DROP COLUMN ${id(mustHave(name(op.name, 'column')))}${op.cascade ? ' CASCADE' : ''}`, `drop column ${op.name}`); break;
      case 'addIndex': {
        const method = METHODS.includes(op.method) ? op.method : 'btree';
        const n = op.name ? name(op.name, 'index name') : autoName(table, ...(op.columns || []), op.unique ? 'key' : 'idx');
        const where = op.where ? ` WHERE ${expr(op.where, 'index WHERE')}` : '';
        add(`CREATE ${op.unique ? 'UNIQUE ' : ''}INDEX ${op.concurrently ? 'CONCURRENTLY ' : ''}${id(n)} ON ${q}${method !== 'btree' ? ` USING ${method}` : ''} (${cols(op.columns, 'Index')})${where}`, `index ${n}`, op.concurrently ? { concurrent: true } : null);
        break;
      }
      case 'dropIndex': add(`DROP INDEX ${op.concurrently ? 'CONCURRENTLY ' : ''}${P.qname(schema, name(op.name, 'index'))}`, `drop index ${op.name}`, op.concurrently ? { concurrent: true } : null); break;
      case 'addPrimaryKey': add(`ALTER TABLE ${q} ADD ${op.name ? `CONSTRAINT ${id(name(op.name))} ` : ''}PRIMARY KEY (${cols(op.columns, 'Primary key')})`, 'primary key'); break;
      case 'addUnique': add(`ALTER TABLE ${q} ADD ${op.name ? `CONSTRAINT ${id(name(op.name))} ` : ''}UNIQUE (${cols(op.columns, 'Unique')})`, `unique ${(op.columns || []).join(', ')}`); break;
      case 'addCheck': add(`ALTER TABLE ${q} ADD ${op.name ? `CONSTRAINT ${id(name(op.name))} ` : ''}CHECK (${expr(op.expr, 'Check')})${op.notValid ? ' NOT VALID' : ''}`, 'check'); break;
      case 'addForeignKey': {
        const del = ACTIONS.includes(String(op.onDelete || '').toUpperCase()) ? String(op.onDelete).toUpperCase() : 'NO ACTION';
        const upd = ACTIONS.includes(String(op.onUpdate || '').toUpperCase()) ? String(op.onUpdate).toUpperCase() : 'NO ACTION';
        const ref = P.qname(name(op.refSchema || schema, 'schema'), name(op.refTable, 'referenced table'));
        if ((op.columns || []).length !== (op.refColumns || []).length) throw err('Foreign key: as many referenced columns as columns');
        add(`ALTER TABLE ${q} ADD ${op.name ? `CONSTRAINT ${id(name(op.name))} ` : ''}FOREIGN KEY (${cols(op.columns, 'Foreign key')}) REFERENCES ${ref} (${cols(op.refColumns, 'Referenced')})${del !== 'NO ACTION' ? ` ON DELETE ${del}` : ''}${upd !== 'NO ACTION' ? ` ON UPDATE ${upd}` : ''}${op.notValid ? ' NOT VALID' : ''}`, `foreign key → ${op.refTable}`);
        break;
      }
      case 'dropConstraint': add(`ALTER TABLE ${q} DROP CONSTRAINT ${id(name(op.name, 'constraint'))}${op.cascade ? ' CASCADE' : ''}`, `drop ${op.name}`); break;
      case 'renameTable': add(`ALTER TABLE ${q} RENAME TO ${id(name(op.name, 'new table name'))}`, `rename to ${op.name}`); break;
      case 'setSchema': add(`ALTER TABLE ${q} SET SCHEMA ${id(name(op.schema, 'schema'))}`, `move to ${op.schema}`); break;
      case 'comment': add(`COMMENT ON TABLE ${q} IS ${op.text ? lit(op.text) : 'NULL'}`, 'table comment'); break;
      case 'duplicate': {
        const n = P.qname(name(op.schema || schema, 'schema'), name(op.name, 'new table name'));
        add(`CREATE TABLE ${n} (LIKE ${q} INCLUDING ALL)`, `copy structure to ${op.name}`);
        if (op.withData) add(`INSERT INTO ${n} SELECT * FROM ${q}`, 'copy the rows');
        break;
      }
      case 'enableTrigger': add(`ALTER TABLE ${q} ${op.enable ? 'ENABLE' : 'DISABLE'} TRIGGER ${id(name(op.name, 'trigger'))}`, `${op.enable ? 'enable' : 'disable'} trigger ${op.name}`); break;
      default: throw err(`Unknown change: ${op && op.op}`);
    }
  }
  if (!q && ops.some(o => o.op !== 'createTable')) throw err('Which table?');
  return out;
}

async function plan(name0, dbname, body) {
  const S = require('./pg-studio');
  const creating = (body.ops || []).every(o => o && o.op === 'createTable');
  const structure = creating ? null : await S.structure(name0, dbname, body.schema, body.table);
  return build(body.ops, { schema: body.schema, table: body.table, structure });
}
async function preview(name0, dbname, body = {}) { return { statements: await plan(name0, dbname, body) }; }

/** Run the statements in one transaction (test: rolled back). Which one failed is told by its number. */
async function apply(name0, dbname, body = {}) {
  const S = require('./pg-studio');
  const t = await S.resolve(name0);
  const test = !!body.test;
  if (!test && !t.allowWrite) throw err('This connection is read-only. Turn on "Allow changes" first, or Test the changes (rolled back).', 403, { code: 'READ_ONLY' });
  if (!test && t.production && !body.confirm) throw err('This is marked as production — confirm to change the structure', 409, { code: 'NEEDS_CONFIRM' });
  const stmts = await plan(name0, dbname, body);
  const inTx = stmts.map(s => (test && s.concurrent ? { ...s, sql: s.sql.replace(/ CONCURRENTLY /, ' ') } : s)).filter(s => test || !s.concurrent);
  const after = test ? [] : stmts.filter(s => s.concurrent);
  const mark = 'dg:at:';
  const args = ['-q', '-c', 'BEGIN'];
  inTx.forEach((s, i) => args.push('-c', `\\echo ${mark}${i}`, '-c', s.sql));
  args.push('-c', test ? 'ROLLBACK' : 'COMMIT');
  const r = await S.psql(t, args, { db: dbname || t.dbname, readOnly: false, timeoutMs: 300000 });
  const at = [...String(r.stdout || '').matchAll(/dg:at:(\d+)/g)].map(m => Number(m[1])).pop();
  const clean = (e) => String(e || '').replace(/^psql:(\s*error:)?\s*/gm, '').replace(/^<?stdin>?:\d+:\s*/gm, '').trim();
  if (r.code !== 0) throw err(`${at != null ? `Change ${at + 1} (${inTx[at].label}): ` : ''}${clean(r.stderr) || 'failed'} — nothing was changed.`, 400, { code: 'FAILED', at, statement: at != null ? inTx[at].sql : null });
  for (const s of after) { // CONCURRENTLY, outside the transaction
    const x = await S.psql(t, ['-q', '-c', s.sql], { db: dbname || t.dbname, readOnly: false, timeoutMs: 3600000 });
    if (x.code !== 0) throw err(`The other changes are made; ${s.label} failed: ${clean(x.stderr)}`, 400, { code: 'PARTIAL', statement: s.sql });
  }
  return { ok: true, test, statements: stmts };
}

module.exports = { build, preview, apply, TYPE_RE };
